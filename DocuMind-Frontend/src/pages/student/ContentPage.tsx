import { useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import { Link, useParams, useSearchParams } from 'react-router-dom'
import ReactMarkdown from 'react-markdown'
import DOMPurify from 'dompurify'
import { Check, Clipboard, Download, Search } from 'lucide-react'
import { toast } from 'sonner'
import { downloadLectureFile, getGeneratedNotes, getLecture, getTutorial } from '@/api/lectureApi'
import { Button, Card, Skeleton } from '@/components/ui'
import { EmptyState, PageHeader } from '@/components/common/shared'
import { useClearOnLeave } from '@/utils/useClearOnLeave'

type Tab = 'notes' | 'tutorial'

export default function ContentPage() {
  const { uploadId = '' } = useParams()
  const [params, setParams] = useSearchParams()
  const tab = params.get('tab') === 'tutorial' ? 'tutorial' : 'notes'
  const [query, setQuery] = useState('')
  useClearOnLeave()
  const lecture = useQuery({ queryKey: ['lecture', uploadId], queryFn: () => getLecture(uploadId), gcTime: 0 })
  const content = useQuery({
    queryKey: ['content', uploadId, tab],
    queryFn: () => tab === 'notes' ? getGeneratedNotes(uploadId) : getTutorial(uploadId),
    gcTime: 0, // dropped from the cache as soon as the student leaves the page
  })
  const safe = DOMPurify.sanitize(content.data ?? '', { ALLOWED_TAGS: [] })
  const copy = async () => {
    await navigator.clipboard.writeText(safe)
    toast.success(`${tab === 'notes' ? 'Notes' : 'Study guide'} copied`)
  }

  const status = lecture.data?.status
  const isProcessing = Boolean(lecture.data?.active)
  const isFailed = status === 'failed' || status === 'cancelled'

  const download = async () => {
    try {
      await downloadLectureFile(uploadId, tab === 'notes' ? 'notes' : 'tutorial', `${lecture.data?.title || 'lecture'}-${tab === 'notes' ? 'notes' : 'study-guide'}.pdf`)
    } catch (error) {
      toast.error(error instanceof Error ? error.message : 'Download failed')
    }
  }

  return <>
    <PageHeader eyebrow={lecture.data?.course || 'Learning materials'} title={lecture.data?.title || 'Lecture materials'} description={isProcessing ? 'Still generating · open the progress page to follow it' : isFailed ? 'Processing did not finish' : 'Generated by AI · Completed'} action={<div className="flex flex-wrap gap-2"><Button variant="secondary" onClick={download}><Download className="h-4 w-4" />Download PDF</Button><Link to={`/quiz/${uploadId}`}><Button>Take quiz</Button></Link></div>} />
    <div className="mb-6 flex gap-1 overflow-x-auto rounded-xl border border-slate-200 bg-white p-1 dark:border-slate-800 dark:bg-slate-900" role="tablist">
      {([['notes', 'Summary notes'], ['tutorial', 'Tutorial / study guide']] as [Tab, string][]).map(([id, label]) => <button key={id} role="tab" aria-selected={tab === id} onClick={() => setParams({ tab: id })} className={`min-h-10 whitespace-nowrap rounded-lg px-4 text-sm font-semibold ${tab === id ? 'bg-primary text-white' : 'text-slate-600 hover:bg-slate-50 dark:text-slate-300 dark:hover:bg-slate-800'}`}>{label}</button>)}
    </div>
    <Card className="min-w-0 p-5 sm:p-8">
      {content.isLoading ? <div className="space-y-4"><Skeleton className="h-8 w-2/3" /><Skeleton className="h-4 w-full" /><Skeleton className="h-4 w-[90%]" /><Skeleton className="h-40 w-full" /></div> : !content.data ? <EmptyState
          title={isProcessing ? 'Still generating…' : isFailed ? 'Processing did not finish' : 'No content available'}
          description={isProcessing ? 'Your learning materials are being created. Check the progress page.' : isFailed ? (lecture.data?.errorMessage || 'This lecture could not be processed.') : 'This material was not requested for this lecture, or has not been generated yet.'}
          action={isProcessing || isFailed ? <Link to={`/processing/${uploadId}`}><Button>{isProcessing ? 'View progress' : 'Open processing page'}</Button></Link> : undefined}
        /> : <>
        <div className="mb-6 flex flex-col gap-3 border-b border-slate-200 pb-5 sm:flex-row sm:items-center sm:justify-between dark:border-slate-800">
          <label className="relative block flex-1"><span className="sr-only">Search within {tab}</span><Search className="absolute left-3 top-3.5 h-4 w-4 text-slate-400" /><input className="field pl-10" placeholder={`Search within ${tab}…`} value={query} onChange={e => setQuery(e.target.value)} /></label>
          <Button variant="secondary" onClick={copy}><Clipboard className="h-4 w-4" />Copy</Button>
        </div>
        {query && <p className="mb-4 rounded-xl bg-blue-50 p-3 text-sm text-blue-700 dark:bg-blue-950 dark:text-blue-300">Searching within {tab} for “{query}”</p>}
        <ReactMarkdown components={{ h2: ({ children }) => <h2 className="mt-8 text-2xl font-bold first:mt-0">{children}</h2>, h3: ({ children }) => <h3 className="mt-6 text-xl font-semibold">{children}</h3>, p: ({ children }) => <p className="mt-4 leading-7 muted">{children}</p>, ul: ({ children }) => <ul className="mt-4 list-disc space-y-2 pl-6 muted">{children}</ul>, ol: ({ children }) => <ol className="mt-4 list-decimal space-y-2 pl-6 muted">{children}</ol> }}>{content.data}</ReactMarkdown>
        <div className="flex items-center justify-between border-t border-slate-200 pt-5 text-sm dark:border-slate-800"><span className="flex items-center gap-2 text-emerald-700"><Check className="h-4 w-4" />Content saved automatically</span><Button variant="ghost" onClick={() => window.scrollTo({ top: 0, behavior: 'smooth' })}>Back to top</Button></div>
      </>}
    </Card>
  </>
}
